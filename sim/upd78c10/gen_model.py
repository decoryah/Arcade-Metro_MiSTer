#!/usr/bin/env python3
"""Build the golden model of the uPD78C10 from MAME 0.289's own sources (BSD-3-Clause, Juergen Buchmueller).

The instruction handlers (upd7810_opcodes.cpp), the opcode tables (upd7810_table.cpp) and the macros are used unchanged; the core pieces of upd7810.cpp
(ports, interrupts, timers, serial, the run loop) are cut out by function name; around them sit a small shim header (`upd7810.h` here replaces MAME's, so the
device framework is not needed) and `model.cpp`, the Metro sound-CPU environment (ROM banking, port A latch, port B strobes, RXD shift latch).

  python gen_model.py          writes model/gen/*  (needs ref/mame/src/devices/cpu/upd7810/, fetched from the mame0289 tag)
"""
import os
import re
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), '..', 'tools'))
import paths as T  # noqa: E402

SRC = os.path.join(T.BASE, 'ref', 'mame', 'src', 'devices', 'cpu', 'upd7810')
GEN = os.path.join(HERE, 'model', 'gen')

CORE_FUNCS = ['RP', 'read_pc', 'WP', 'write_pc', 'write_smh', 'upd7810_take_irq', 'upd7810_to_output_change', 'upd7810_co0_output_change',
              'upd7810_co1_output_change', 'upd7810_write_EOM', 'upd7810_write_TXB', 'upd7810_sio_output', 'upd7810_sio_input',
              'upd7810_handle_timer0', 'upd7810_handle_timer1', 'update_sio', 'handle_timers', 'device_reset', 'execute_run', 'execute_set_input']


def read(name):
    return open(os.path.join(SRC, name), encoding='utf-8', newline='').read().replace('\r\n', '\n')


def extract(lines, name):
    pat = re.compile(r'^(?:[\w:<>\*& ]+?\s+)?upd7810_device::' + re.escape(name) + r'\(')
    for i, l in enumerate(lines):
        if pat.match(l):
            j = i
            while lines[j] != '}':
                j += 1
            return lines[i:j + 1]
    raise SystemExit('function not found: ' + name)


HEADER = r'''// Generated by gen_model.py: stands in for MAME's upd7810.h (no device framework).  Members and flag values are MAME 0.289's.
#pragma once
#include "emu.h"

class upd7810_device
{
public:
	enum { CY = 0x01, F1 = 0x02, L0 = 0x04, L1 = 0x08, HC = 0x10, SK = 0x20, Z = 0x40, F7 = 0x80 };
	enum { INTFNMI = 0x0001, INTFT0 = 0x0002, INTFT1 = 0x0004, INTF1 = 0x0008, INTF2 = 0x0010, INTFE0 = 0x0020, INTFE1 = 0x0040, INTFEIN = 0x0080,
	       INTFAD = 0x0100, INTFSR = 0x0200, INTFST = 0x0400, INTER = 0x0800, INTOV = 0x1000, INTF0 = 0x2000 };
	enum { INTAN4 = 0x0001, INTAN5 = 0x0002, INTAN6 = 0x0004, INTAN7 = 0x0008, INTSB = 0x0010 };
	enum { UPD7810_INTF1 = 1, UPD7810_INTF2 = 2 };   // irqline numbers used by execute_set_input
	enum { INPUT_LINE_NMI = 32 };

	typedef void (upd7810_device::*opcode_func)();
	struct opcode_s { opcode_func opfunc; uint8_t oplen; uint8_t cycles; uint8_t cycles_skip; uint8_t mask_l0_l1; };

	// create with `new upd7810_device()` (value-initialised: every member starts at zero)
	const char *tag() const { return "audiocpu"; }
	void standard_irq_callback(int, uint16_t) {}

	// environment hooks (model.cpp fills these in)
	Mem m_program, m_opcodes, m_io;
	devcb_write_line  m_to_func, m_co0_func, m_co1_func, m_txd_func;
	devcb_read_line   m_rxd_func;
	devcb_read8       m_an_func[8];
	devcb_read8       m_pa_in_cb, m_pb_in_cb, m_pc_in_cb, m_pd_in_cb, m_pf_in_cb, m_pt_in_cb;
	devcb_write8      m_pa_out_cb, m_pb_out_cb, m_pc_out_cb, m_pd_out_cb, m_pf_out_cb;
	RamView m_ram_view;

	void device_reset();
	void execute_run();
	void execute_set_input(int irqline, int state);
	void configure_ops();

	void update_sio(int cycles);
	void handle_timers(int cycles);
	void upd7810_take_irq();
	void upd7810_handle_timer0(int cycles, int clkdiv);
	void upd7810_handle_timer1(int cycles, int clkdiv);
	void upd7810_to_output_change(int state);
	void upd7810_co0_output_change();
	void upd7810_co1_output_change();
	void upd7810_write_EOM();
	void upd7810_write_TXB();
	void upd7810_sio_output();
	void upd7810_sio_input();
	uint8_t RP(offs_t port);
	void WP(offs_t port, uint8_t data);
	uint8_t read_pc();
	void write_pc(uint8_t data);
	void write_smh(uint8_t data);

@HANDLERS@
@TABLES@
	const struct opcode_s *m_opXX, *m_op48, *m_op4C, *m_op4D, *m_op60, *m_op64, *m_op70, *m_op74;

	PAIR m_ppc, m_pc, m_sp;
	uint8_t m_op, m_op2, m_iff, m_iff_pending, m_psw;
	PAIR m_ea, m_va, m_bc, m_de, m_hl, m_ea2, m_va2, m_bc2, m_de2, m_hl2;
	PAIR m_cnt, m_tm, m_ecnt, m_etm;
	uint8_t m_ma, m_mb, m_mcc, m_mc, m_mm, m_mf, m_mt, m_tmm, m_etmm, m_eom, m_sml, m_smh, m_panm, m_anm, m_mkl, m_mkh, m_zcm;
	uint8_t m_pa_in, m_pb_in, m_pc_in, m_pd_in, m_pf_in, m_pa_out, m_pb_out, m_pc_out, m_pd_out, m_pf_out;
	uint8_t m_pa_pullups, m_pb_pullups, m_pc_pullups, m_pd_pullups, m_pf_pullups;
	uint8_t m_cr[4];
	uint8_t m_txb, m_rxb, m_txd, m_rxd, m_sck, m_ti, m_to, m_ci, m_lv0, m_lv1, m_co0, m_co1;
	uint16_t m_irr, m_itf;
	int m_nmi, m_int1, m_int2;
	uint8_t m_halt;
	uint16_t m_txs, m_rxs;
	uint8_t m_txcnt, m_rxcnt, m_txbuf;
	int32_t m_ovc0, m_ovc1, m_ovce, m_ovcf, m_ovcs;
	uint8_t m_edges;
	int32_t m_adcnt, m_adtot;
	uint8_t m_tmpcr, m_shdone, m_adout, m_adin, m_adrange;
	int m_icount;
};
'''


def main():
    os.makedirs(GEN, exist_ok=True)
    for f in ('upd7810_opcodes.cpp', 'upd7810_table.cpp', 'upd7810_macros.h'):
        shutil.copyfile(os.path.join(SRC, f), os.path.join(GEN, f))
    ops = read('upd7810_opcodes.cpp')
    handlers = sorted(set(re.findall(r'^void upd7810_device::(\w+)\(\)', ops, re.M)))
    tbl = read('upd7810_table.cpp')
    tables = re.findall(r'^const struct upd7810_device::opcode_s upd7810_device::(\w+)\[256\]', tbl, re.M)
    hdr = HEADER.replace('@HANDLERS@', '\n'.join('\tvoid %s();' % h for h in handlers))
    hdr = hdr.replace('@TABLES@', '\n'.join('\tstatic const struct opcode_s %s[256];' % t for t in tables))
    open(os.path.join(GEN, 'upd7810.h'), 'w', newline='\n').write(hdr)
    main_src = read('upd7810.cpp').split('\n')
    out = ['// Generated by gen_model.py: the core of MAME 0.289 upd7810.cpp (BSD-3-Clause), cut out function by function.',
           '#include "emu.h"', '#include "upd7810.h"', '#include "upd7810_macros.h"', '',
           '#define PAR7(n) ((((n)>>6)^((n)>>5)^((n)>>4)^((n)>>3)^((n)>>2)^((n)>>1)^((n)))&1)',
           '#define PAR8(n) ((((n)>>7)^((n)>>6)^((n)>>5)^((n)>>4)^((n)>>3)^((n)>>2)^((n)>>1)^((n)))&1)', '']
    for name in CORE_FUNCS:
        out += extract(main_src, name) + ['']
    out += ['void upd7810_device::configure_ops()', '{', '\tm_opXX = s_opXX_7810; m_op48 = s_op48; m_op4C = s_op4C; m_op4D = s_op4D;',
            '\tm_op60 = s_op60; m_op64 = s_op64; m_op70 = s_op70; m_op74 = s_op74;', '}', '']
    open(os.path.join(GEN, 'core_extract.cpp'), 'w', newline='\n').write('\n'.join(out))
    print('handlers: %d, tables: %d, core functions: %d' % (len(handlers), len(tables), len(CORE_FUNCS)))


if __name__ == '__main__':
    main()
